const assert = require('node:assert/strict');
const { ClassroomCallStore, participantLimit, signalPayload } = require('../src/services/classroomCallStore');
const { assertClassAccess } = require('../src/routes/classroomCalls');
const user = id => ({ id, name: id, role: 'MEMBER' });
const key = 'test_join_key_12345';
const rejects = (action, status) => assert.throws(action, e => e.status === status);
(async () => {
  let now = 100; const store = new ClassroomCallStore({ now: () => now, maxParticipants: 2 });
  assert.equal(participantLimit(), 4); assert.throws(() => participantLimit('99'));
  const a = store.join('class', user('a'), key);
  assert.equal(store.join('class', user('a'), key).sessionId, a.sessionId);
  rejects(() => store.join('class', user('a'), key+'other'), 409);
  const b = store.join('class', user('b'), key);
  rejects(() => store.join('class', user('c'), key), 409);
  rejects(() => store.poll('class', a.sessionId, 'b', 0), 403);
  rejects(() => store.poll('class', a.sessionId, 'a', 1), 400);
  rejects(() => store.signal('class', a.sessionId, 'a', b.sessionId, { type: 'offer', sdp: 'x'.repeat(65537) }), 400);
  rejects(() => store.signal('class', a.sessionId, 'a', a.sessionId, { type: 'offer', sdp: 'hello' }), 404);
  store.signal('class', a.sessionId, 'a', b.sessionId, { type: 'offer', sdp: 'hello' });
  let events = store.poll('class', b.sessionId, 'b', 0);
  assert.equal(events.events.length, 1); assert.equal(events.events[0].from, a.sessionId);
  assert.equal(store.poll('class', b.sessionId, 'b', events.cursor).events.length, 0);
  assert.equal(store.poll('class', a.sessionId, 'a', 0).events.length, 0);
  rejects(() => signalPayload({ type: 'ice', candidate: { candidate: 'x', sdpMLineIndex: -1 } }), 400);
  for (let i=0;i<179;i++) store.signal('class', a.sessionId, 'a', b.sessionId, { type: 'ice', candidate: { candidate: 'x' } });
  rejects(() => store.signal('class', a.sessionId, 'a', b.sessionId, { type: 'ice', candidate: { candidate: 'x' } }), 429);
  store.leave('class', a.sessionId, 'a'); assert.equal(store.poll('class', b.sessionId, 'b', events.cursor).participants.length, 1);
  now += 45001; rejects(() => store.poll('class', b.sessionId, 'b', 0), 410); assert.equal(store.rooms.size, 0);
  let queried=false;
  await assert.rejects(assertClassAccess(async()=>{queried=true;return {rows:[]};},user('a'),'../bad'),e=>e.status===400); assert.equal(queried,false);
  await assert.rejects(assertClassAccess(async(sql,args)=>{assert(sql.includes('group_memberships')); assert.deepEqual(args,['class','a','MEMBER']); return {rows:[]};},user('a'),'class'),e=>e.status===403);
  await assertClassAccess(async()=>({rows:[{id:'class'}]}),user('a'),'class');
  console.log('Classroom signaling bounds, session ownership, replay cursor, TTL, room limit, and membership guard passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
