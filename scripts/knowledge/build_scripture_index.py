#!/usr/bin/env python3
"""Builds the verse-range index used to reject non-existent chapters and verses.

Source: src/main/assets/bible/text/KJV.tsv.gz (bundled, public domain KJV, one verse per line:
bookNumber, chapter, verse, text). The index records, for every book, the verse count of every chapter,
plus a SHA-256 of the source file so a stale index is detectable. Nothing is typed by hand.

Usage: python3 scripts/knowledge/build_scripture_index.py
"""
import gzip
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, "src/main/assets/bible/text/KJV.tsv.gz")
OUT = os.path.join(ROOT, "src/main/assets/ai/library/scripture/kjv-verse-counts.json")

BOOK_NAMES = [
    "Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy", "Joshua", "Judges", "Ruth",
    "1 Samuel", "2 Samuel", "1 Kings", "2 Kings", "1 Chronicles", "2 Chronicles", "Ezra", "Nehemiah",
    "Esther", "Job", "Psalms", "Proverbs", "Ecclesiastes", "Song of Solomon", "Isaiah", "Jeremiah",
    "Lamentations", "Ezekiel", "Daniel", "Hosea", "Joel", "Amos", "Obadiah", "Jonah", "Micah", "Nahum",
    "Habakkuk", "Zephaniah", "Haggai", "Zechariah", "Malachi", "Matthew", "Mark", "Luke", "John", "Acts",
    "Romans", "1 Corinthians", "2 Corinthians", "Galatians", "Ephesians", "Philippians", "Colossians",
    "1 Thessalonians", "2 Thessalonians", "1 Timothy", "2 Timothy", "Titus", "Philemon", "Hebrews",
    "James", "1 Peter", "2 Peter", "1 John", "2 John", "3 John", "Jude", "Revelation",
]


def build():
    with open(SOURCE, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    books = {}
    verses_seen = 0
    with gzip.open(SOURCE, "rt", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            book_s, chap_s, verse_s, _text = line.split("\t", 3)
            book, chap, verse = int(book_s), int(chap_s), int(verse_s)
            chapters = books.setdefault(book, {})
            # Verses are stored in order; the count of a chapter is its highest verse number.
            if verse > chapters.get(chap, 0):
                chapters[chap] = verse
            verses_seen += 1
    if len(books) != 66:
        raise SystemExit("expected 66 books, found %d" % len(books))
    out_books = []
    for number in range(1, 67):
        chapters = books[number]
        expected = list(range(1, len(chapters) + 1))
        if sorted(chapters) != expected:
            raise SystemExit("book %d has gaps in its chapter numbers" % number)
        out_books.append({
            "book": number,
            "name": BOOK_NAMES[number - 1],
            "chapterVerseCounts": [chapters[c] for c in expected],
        })
    return {
        "_comment": "Generated by scripts/knowledge/build_scripture_index.py. Do not edit by hand. "
                    "Verse counts of the bundled KJV (public domain). Used to reject non-existent chapters "
                    "and verses before any reference is shown or quoted.",
        "translation": "KJV",
        "source": "src/main/assets/bible/text/KJV.tsv.gz",
        "sourceSha256": digest,
        "totalVerses": verses_seen,
        "books": out_books,
    }


if __name__ == "__main__":
    index = build()
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote %s: %d books, %d verses" % (OUT, len(index["books"]), index["totalVerses"]))
    sys.exit(0)
