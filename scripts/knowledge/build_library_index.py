#!/usr/bin/env python3
"""Writes the knowledge library's source register and manifest.

- sources/register.json: every source in scripts/reference/sources.json and its status for the guide
  (approved in approvals.json, or candidate only), with licence and URL copied from that file.
- INDEX.json: the folder map, one entry per part, with the files it holds and their SHA-256.

Nothing here is typed by hand except the part descriptions in PARTS below. Run after any change to the library.
Usage: python3 scripts/knowledge/build_library_index.py
"""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIB = os.path.join(ROOT, "src/main/assets/ai/library")
SOURCES = os.path.join(ROOT, "scripts/reference/sources.json")
APPROVALS = os.path.join(ROOT, "src/main/assets/reference/approvals.json")

PARTS = {
    "scripture": "Verse-count index of the bundled KJV. Rejects references to chapters or verses that do not exist.",
    "doctrine": "Doctrine status register. Topic status only (APPROVED, UNDER_REVIEW, UNDECIDED, DRAFT_PENDING_LEVI). Fail-closed.",
    "kenya": "Kenyan contacts with their verification status, as recorded by Levi.",
    "sources": "Source register: licence, URL and approval status of every reference source.",
}


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def build_register():
    with open(SOURCES, encoding="utf-8") as f:
        data = json.load(f)
    with open(APPROVALS, encoding="utf-8") as f:
        approved = set(json.load(f)["approvedSourceIds"])
    rows = []
    for src in data.get("sources", []):
        rows.append({
            "id": src["id"], "title": src.get("title"), "author": src.get("author"),
            "category": src.get("category"), "licence": src.get("licence"),
            "licenceUrl": src.get("licenceUrl"), "sourceUrl": src.get("sourceUrl"),
            "theologyTag": src.get("theologyTag"), "tier": src.get("tier"),
            "status": "APPROVED_FOR_GUIDE" if src["id"] in approved else "NOT_APPROVED",
        })
    for cand in data.get("candidates", []) or []:
        if isinstance(cand, dict):
            rows.append({
                "id": cand.get("id"), "title": cand.get("title"), "author": cand.get("author"),
                "category": cand.get("category"), "licence": cand.get("licence"),
                "licenceUrl": cand.get("licenceUrl"), "sourceUrl": cand.get("sourceUrl"),
                "theologyTag": cand.get("theologyTag"), "tier": "candidate",
                "status": "CANDIDATE_NOT_APPROVED",
            })
    missing = sorted(approved - {r["id"] for r in rows})
    if missing:
        raise SystemExit("approved ids with no source row: %s" % ", ".join(missing))
    return {
        "_comment": "Generated by scripts/knowledge/build_library_index.py from scripts/reference/sources.json "
                    "and src/main/assets/reference/approvals.json. Only APPROVED_FOR_GUIDE sources may be used.",
        "sources": rows,
    }


def build_index():
    parts = []
    for name, description in PARTS.items():
        folder = os.path.join(LIB, name)
        files = []
        for dirpath, _dirs, names in os.walk(folder):
            for n in sorted(names):
                full = os.path.join(dirpath, n)
                rel = os.path.relpath(full, LIB).replace(os.sep, "/")
                files.append({"path": rel, "sha256": sha256(full), "bytes": os.path.getsize(full)})
        parts.append({"part": name, "description": description, "files": sorted(files, key=lambda x: x["path"])})
    return {
        "_comment": "Manifest of the knowledge library. Generated, do not edit by hand. The runtime loader for the "
                    "signed knowledge package is unchanged; these files are read by host tests and by the engine "
                    "owner when it wires them in.",
        "libraryVersion": "0.1.0",
        "parts": parts,
        "notYetInLibrary": [
            "Cross-references, dictionaries and places: still in assets/reference/reference.db.gz (loaded by ReferenceIndex).",
            "Commentaries: still in assets/reference/reference-commentaries.db.gz (optional; loaded by ReferenceIndex).",
            "Bible text: still in assets/bible/text (loaded by the Bible reader and OfflineScriptureLookup).",
            "Operating files: still in assets/ai/guide (loaded by GuideDocs).",
        ],
    }


def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=1)
        f.write("\n")


if __name__ == "__main__":
    write(os.path.join(LIB, "sources/register.json"), build_register())
    # Build the index last so it hashes the register that was just written.
    write(os.path.join(LIB, "INDEX.json"), build_index())
    print("library index written under %s" % LIB)
