"""Generates RoadBank.java from road_src.py. Run check_road.py first."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import road_src  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "..", "src", "main", "java", "org", "perazimchurch", "app",
                   "domain", "games", "catalog", "RoadBank.java")


def java(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(name, rows):
    lines = []
    for q, answer, w1, w2, w3, ref, expl in rows:
        fields = "~".join([q, answer, w1, w2, w3, ref, expl])
        assert "~" not in "".join([q, answer, w1, w2, w3, ref, expl]) or fields.count("~") == 6
        lines.append("        " + java(fields) + ",")
    return "    static final String[] %s = {\n%s\n    };\n" % (name, "\n".join(lines))


def main():
    body = "\n".join([table("EASY", road_src.EASY), table("MEDIUM", road_src.MEDIUM), table("HARD", road_src.HARD)])
    text = ("package org.perazimchurch.app.domain.games.catalog;\n\n"
            "/** Road to Jerusalem stages. Generated by scripts/games/content/build_road_java.py; do not edit. */\n"
            "final class RoadBank {\n    private RoadBank() {}\n\n" + body + "}\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
