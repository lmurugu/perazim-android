"""Generates MemoryBank.java from assets/games/memory_sets.json. Run after editing the source."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "src", "main", "assets", "games", "memory_sets.json")
OUT = os.path.join(HERE, "..", "..", "..", "src", "main", "java", "org", "perazimchurch", "app",
                   "domain", "games", "catalog", "MemoryBank.java")

TEMPLATE = """package org.perazimchurch.app.domain.games.catalog;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Memory Match pair sets. GENERATED by scripts/games/content/build_memory_java.py from
 * assets/games/memory_sets.json. Edit the source, then re-run the script.
 */
public final class MemoryBank {

    /** One matching pair with the verse it comes from. */
    public static final class Pair {
        public final String a;
        public final String b;
        public final String reference;

        Pair(String a, String b, String reference) {
            this.a = a;
            this.b = b;
            this.reference = reference;
        }
    }

    /** A set of pairs drawn together. */
    public static final class PairSet {
        public final String id;
        public final String title;
        public final List<Pair> pairs;

        PairSet(String id, String title, Pair[] pairs) {
            this.id = id;
            this.title = title;
            this.pairs = Collections.unmodifiableList(Arrays.asList(pairs));
        }
    }

    public static final List<PairSet> SETS = Collections.unmodifiableList(Arrays.asList(
@@ROWS@@
    ));

    private static PairSet set(String id, String title, Pair[] pairs) {
        return new PairSet(id, title, pairs);
    }

    private static Pair p(String a, String b, String reference) {
        return new Pair(a, b, reference);
    }

    private MemoryBank() {}
}
"""


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    rows = []
    for s in data["sets"]:
        pairs = ", ".join("p(%s, %s, %s)" % (lit(p["a"]), lit(p["b"]), lit(p["reference"])) for p in s["pairs"])
        rows.append("        set(%s, %s, new Pair[] {%s})," % (lit(s["id"]), lit(s["title"]), pairs))
    rows[-1] = rows[-1].rstrip(",")
    open(OUT, "w", encoding="utf-8").write(TEMPLATE.replace("@@ROWS@@", "\n".join(rows)))
    print("wrote", OUT, len(rows), "sets")


if __name__ == "__main__":
    main()
