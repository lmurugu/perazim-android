"""Generates WordSearchBank.java from assets/games/word_search_themes.json. Run after editing the source."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "src", "main", "assets", "games", "word_search_themes.json")
OUT = os.path.join(HERE, "..", "..", "..", "src", "main", "java", "org", "perazimchurch", "app",
                   "domain", "games", "catalog", "WordSearchBank.java")

TEMPLATE = """package org.perazimchurch.app.domain.games.catalog;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Word search themes. GENERATED by scripts/games/content/build_word_search_java.py from
 * assets/games/word_search_themes.json. Edit the JSON, then re-run the script.
 */
public final class WordSearchBank {

    /** One word with the reference where it appears. */
    public static final class Entry {
        public final String word;
        public final String reference;

        Entry(String word, String reference) {
            this.word = word;
            this.reference = reference;
        }
    }

    /** A themed puzzle: a title and the words to find, in a fixed order. */
    public static final class Theme {
        public final String id;
        public final String title;
        public final List<Entry> words;

        Theme(String id, String title, Entry[] words) {
            this.id = id;
            this.title = title;
            this.words = Collections.unmodifiableList(Arrays.asList(words));
        }
    }

    public static final List<Theme> THEMES = Collections.unmodifiableList(Arrays.asList(
@@ROWS@@
    ));

    private static Theme theme(String id, String title, Entry[] words) {
        return new Theme(id, title, words);
    }

    private static Entry w(String word, String reference) {
        return new Entry(word, reference);
    }

    private WordSearchBank() {}
}
"""


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    rows = []
    for t in data["themes"]:
        words = ", ".join("w(%s, %s)" % (lit(x["word"]), lit(x["reference"])) for x in t["words"])
        rows.append("        theme(%s, %s, new Entry[] {%s})," % (lit(t["id"]), lit(t["title"]), words))
    rows[-1] = rows[-1].rstrip(",")
    java = TEMPLATE.replace("@@ROWS@@", "\n".join(rows))
    open(OUT, "w", encoding="utf-8").write(java)
    print("wrote", OUT, len(rows), "themes")


if __name__ == "__main__":
    main()
