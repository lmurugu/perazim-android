"""Generates the Who am I? Java bank from assets/games/who_am_i.json so the pure-Java game code
and its unit tests share one source of truth. Run after editing the JSON; the check script
verifies references."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "src", "main", "assets", "games", "who_am_i.json")
OUT = os.path.join(HERE, "..", "..", "..", "src", "main", "java", "org", "perazimchurch", "app",
                   "domain", "games", "catalog", "WhoAmIBank.java")

TEMPLATE = """package org.perazimchurch.app.domain.games.catalog;

import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Who am I? people with clues. GENERATED by scripts/games/content/build_who_am_i_java.py from
 * assets/games/who_am_i.json. Edit the JSON, then re-run the script.
 */
public final class WhoAmIBank {

    /** One person to guess. Clues run from vague to specific. */
    public static final class Person {
        public final String answer;
        public final List<String> aliases;
        public final String reference;
        public final String explanation;
        public final List<String> clues;
        public final String hint;

        Person(String answer, String[] aliases, String reference, String explanation,
               String[] clues, String hint) {
            this.answer = answer;
            this.aliases = Collections.unmodifiableList(Arrays.asList(aliases));
            this.reference = reference;
            this.explanation = explanation;
            this.clues = Collections.unmodifiableList(Arrays.asList(clues));
            this.hint = hint;
        }
    }

    public static final List<Person> PEOPLE = Collections.unmodifiableList(Arrays.asList(
@@ROWS@@
    ));

    private static Person person(String answer, String[] aliases, String reference,
                                 String explanation, String[] clues, String hint) {
        return new Person(answer, aliases, reference, explanation, clues, hint);
    }

    private WhoAmIBank() {}
}
"""


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def arr(items):
    return "new String[] {" + ", ".join(lit(i) for i in items) + "}" if items else "new String[0]"


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    rows = []
    for p in data["people"]:
        rows.append("        person(" + lit(p["answer"]) + ", " + arr(p["aliases"]) + ", "
                    + lit(p["reference"]) + ", " + lit(p["explanation"]) + ", "
                    + arr(p["clues"]) + ", " + lit(p["hint"]) + "),")
    rows[-1] = rows[-1].rstrip(",")
    java = TEMPLATE.replace("@@ROWS@@", "\n".join(rows))
    open(OUT, "w", encoding="utf-8").write(java)
    print("wrote", OUT, len(rows), "people")


if __name__ == "__main__":
    main()
