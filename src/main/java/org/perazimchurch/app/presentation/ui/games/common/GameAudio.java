package org.perazimchurch.app.presentation.ui.games.common;

import android.content.Context;
import android.content.SharedPreferences;
import android.content.res.AssetFileDescriptor;
import android.media.AudioAttributes;
import android.media.AudioFocusRequest;
import android.media.AudioManager;
import android.media.MediaPlayer;
import android.media.SoundPool;
import android.os.Build;
import android.os.Handler;
import android.os.Looper;

import java.io.IOException;
import java.util.HashMap;
import java.util.Map;

/**
 * Shared game sound design: a looping music bed per game and short sound effects for every game.
 *
 * <p>Effects play through {@link SoundPool}; music loops through {@link MediaPlayer}. All assets are
 * bundled under {@code assets/games/audio/} (generated by {@code tools/game_audio/synth.py}), so
 * everything works offline. Volumes and mutes are stored per account under the owner's score prefix.
 * Music ducks while an effect plays, stops on audio focus loss, pauses when the app goes to the
 * background, and stays silent when the phone is in silent or vibrate mode.
 *
 * <p>Every call is safe to make when audio is unavailable: failures are swallowed and the game runs
 * without sound. See docs/GAME_AUDIO.md.
 */
public final class GameAudio {

    /** Short sound effects shared by every game. */
    public enum Sfx {
        TAP("sfx_tap"), CORRECT("sfx_correct"), WRONG("sfx_wrong"), STAR("sfx_star"),
        COMPLETE("sfx_complete"), COMBO_1("sfx_combo1"), COMBO_2("sfx_combo2"), COMBO_3("sfx_combo3"),
        HINT("sfx_hint");

        final String asset;
        Sfx(String asset) { this.asset = asset; }
    }

    /** Asset folder inside the app's assets. */
    static final String DIR = "games/audio/";
    /** Music track for the games hub and for any game without its own track. */
    static final String HUB_TRACK = "hub";

    /** Game id to music track. Track names match {@code music_<track>.ogg}. */
    private static final Map<String, String> MUSIC = new HashMap<>();
    static {
        for (String id : new String[] {"bible_quiz", "who_am_i", "verse_builder", "ladder_of_faith",
                "word_search", "memory_match", "story_timeline", "road_to_jerusalem", "old_or_new",
                "who_said_it", "fill_the_gap", "vine_words", "lamp_slide", "story_mosaic"}) {
            MUSIC.put(id, id);
        }
    }

    /** The music track for a game id, or the hub track when the game has none. */
    public static String trackFor(String gameId) {
        String track = gameId == null ? null : MUSIC.get(gameId);
        return track == null ? HUB_TRACK : track;
    }

    private static final String KEY_MUSIC_ON = "audio.music_on";
    private static final String KEY_SFX_ON = "audio.sfx_on";
    private static final String KEY_MUSIC_VOL = "audio.music_vol";
    private static final String KEY_SFX_VOL = "audio.sfx_vol";
    private static final float DUCK_LEVEL = 0.35f;
    private static final long DUCK_MS = 350L;

    private static GameAudio instance;

    private final Context appContext;
    private final Handler main = new Handler(Looper.getMainLooper());
    private SoundPool pool;
    private final Map<Sfx, Integer> loaded = new HashMap<>();
    private MediaPlayer music;
    private String currentTrack;
    private SharedPreferences settings;
    private String settingsPrefix = "";
    private boolean appInForeground = true;
    private boolean musicPausedByApp;
    private AudioFocusRequest focusRequest;
    private final AudioManager.OnAudioFocusChangeListener focusListener = change -> {
        if (change == AudioManager.AUDIOFOCUS_LOSS) {
            stopMusic();
        } else if (change == AudioManager.AUDIOFOCUS_LOSS_TRANSIENT) {
            pauseMusic();
        } else if (change == AudioManager.AUDIOFOCUS_GAIN) {
            resumeMusic();
        }
    };
    private final Runnable unduck = this::restoreMusicVolume;

    private GameAudio(Context context) {
        this.appContext = context.getApplicationContext();
    }

    /** The shared instance. Pass any context. */
    public static synchronized GameAudio get(Context context) {
        if (instance == null) instance = new GameAudio(context);
        return instance;
    }

    /** Binds the account's settings. {@code prefix} is the owner's score prefix from GameContext. */
    public synchronized void bindAccount(SharedPreferences prefs, String prefix) {
        this.settings = prefs;
        this.settingsPrefix = prefix == null ? "" : prefix;
    }

    // ---- Settings (per account) ----

    public boolean isMusicOn() { return flag(KEY_MUSIC_ON, true); }
    public boolean isSfxOn() { return flag(KEY_SFX_ON, true); }
    /** Music volume 0 to 100. */
    public int musicVolume() { return intValue(KEY_MUSIC_VOL, 60); }
    /** Effects volume 0 to 100. */
    public int sfxVolume() { return intValue(KEY_SFX_VOL, 80); }

    public void setMusicOn(boolean on) { put(KEY_MUSIC_ON, on); if (on) playCurrent(); else stopMusic(); }
    public void setSfxOn(boolean on) { put(KEY_SFX_ON, on); }
    public void setMusicVolume(int percent) { put(KEY_MUSIC_VOL, clamp(percent)); applyMusicVolume(1f); }
    public void setSfxVolume(int percent) { put(KEY_SFX_VOL, clamp(percent)); }

    private boolean flag(String key, boolean fallback) {
        return settings == null ? fallback : settings.getBoolean(settingsPrefix + key, fallback);
    }

    private int intValue(String key, int fallback) {
        return settings == null ? fallback : settings.getInt(settingsPrefix + key, fallback);
    }

    private void put(String key, Object value) {
        if (settings == null) return;
        SharedPreferences.Editor editor = settings.edit();
        if (value instanceof Boolean) editor.putBoolean(settingsPrefix + key, (Boolean) value);
        else editor.putInt(settingsPrefix + key, (Integer) value);
        editor.apply();
    }

    private static int clamp(int percent) { return Math.max(0, Math.min(100, percent)); }

    // ---- Silent mode ----

    /** False when the ringer is silent or on vibrate; game sounds stay off then. */
    public boolean ringerAudible() {
        try {
            AudioManager am = (AudioManager) appContext.getSystemService(Context.AUDIO_SERVICE);
            return am == null || am.getRingerMode() == AudioManager.RINGER_MODE_NORMAL;
        } catch (RuntimeException e) {
            return true;
        }
    }

    // ---- Effects ----

    /** Plays one effect at normal pitch. Returns false when nothing played (off, silent or unavailable). */
    public boolean play(Sfx sfx) { return playPitched(sfx, 1f); }

    /**
     * Plays an effect at a playback rate. Use rates above 1 for layered pitch-ups: each lit star
     * or each step of a combo sits a little higher than the one before.
     */
    public boolean playPitched(Sfx sfx, float rate) {
        if (sfx == null || !isSfxOn() || !ringerAudible()) return false;
        try {
            SoundPool sounds = ensurePool();
            if (sounds == null) return false;
            Integer id = loaded.get(sfx);
            if (id == null) return false;
            float vol = sfxVolume() / 100f;
            if (vol <= 0f) return false;
            duckMusic();
            sounds.play(id, vol, vol, 1, 0, Math.max(0.5f, Math.min(2f, rate)));
            return true;
        } catch (RuntimeException e) {
            return false;
        }
    }

    /** Combo cue for a streak: 1 to 3 steps, each a semitone higher than the last. */
    public boolean combo(int streak) {
        if (streak <= 0) return false;
        Sfx step = streak == 1 ? Sfx.COMBO_1 : streak == 2 ? Sfx.COMBO_2 : Sfx.COMBO_3;
        return play(step);
    }

    private SoundPool ensurePool() {
        if (pool != null) return pool;
        AudioAttributes attrs = new AudioAttributes.Builder()
                .setUsage(AudioAttributes.USAGE_GAME)
                .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                .build();
        pool = new SoundPool.Builder().setMaxStreams(4).setAudioAttributes(attrs).build();
        for (Sfx sfx : Sfx.values()) {
            try (AssetFileDescriptor fd = appContext.getAssets().openFd(DIR + sfx.asset + ".ogg")) {
                loaded.put(sfx, pool.load(fd, 1));
            } catch (IOException | RuntimeException e) {
                // Missing asset: that effect stays silent.
            }
        }
        return pool;
    }

    private void duckMusic() {
        if (music == null || !music.isPlaying()) return;
        applyMusicVolume(DUCK_LEVEL);
        main.removeCallbacks(unduck);
        main.postDelayed(unduck, DUCK_MS);
    }

    private void restoreMusicVolume() { applyMusicVolume(1f); }

    private void applyMusicVolume(float factor) {
        if (music == null) return;
        float vol = musicVolume() / 100f * factor;
        try {
            music.setVolume(vol, vol);
        } catch (RuntimeException ignored) {
            // The player was released while a duck was pending.
        }
    }

    // ---- Music ----

    /**
     * Starts the music for a game screen. Call from the game's launcher, with the hub context. Starts
     * the game's own loop, or the hub loop when the game has none.
     */
    public synchronized void enterGame(String gameId) {
        String track = trackFor(gameId);
        if (!track.equals(currentTrack)) {
            releaseMusic();
            currentTrack = track;
        }
        playCurrent();
    }

    /** Stops the music and releases the player (for example when the app leaves the games). */
    public synchronized void leaveGames() {
        stopMusic();
        currentTrack = null;
    }

    private void playCurrent() {
        if (currentTrack == null || !isMusicOn() || !ringerAudible() || !appInForeground) return;
        if (music == null) {
            try {
                music = new MediaPlayer();
                AssetFileDescriptor fd = appContext.getAssets().openFd(DIR + "music_" + currentTrack + ".ogg");
                music.setDataSource(fd.getFileDescriptor(), fd.getStartOffset(), fd.getLength());
                fd.close();
                music.setLooping(true);
                music.setAudioAttributes(new AudioAttributes.Builder()
                        .setUsage(AudioAttributes.USAGE_GAME)
                        .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC).build());
                music.prepare();
            } catch (IOException | RuntimeException e) {
                releaseMusic();
                return;
            }
        }
        if (!requestFocus()) return;
        applyMusicVolume(1f);
        if (!music.isPlaying()) music.start();
    }

    private boolean requestFocus() {
        AudioManager am = (AudioManager) appContext.getSystemService(Context.AUDIO_SERVICE);
        if (am == null) return true;
        if (Build.VERSION.SDK_INT >= 26) {
            if (focusRequest == null) {
                focusRequest = new AudioFocusRequest.Builder(AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_MAY_DUCK)
                        .setAudioAttributes(new AudioAttributes.Builder()
                                .setUsage(AudioAttributes.USAGE_GAME)
                                .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC).build())
                        .setOnAudioFocusChangeListener(focusListener, main)
                        .build();
            }
            return am.requestAudioFocus(focusRequest) == AudioManager.AUDIOFOCUS_REQUEST_GRANTED;
        }
        return am.requestAudioFocus(focusListener, AudioManager.STREAM_MUSIC,
                AudioManager.AUDIOFOCUS_GAIN_TRANSIENT_MAY_DUCK) == AudioManager.AUDIOFOCUS_REQUEST_GRANTED;
    }

    private void abandonFocus() {
        AudioManager am = (AudioManager) appContext.getSystemService(Context.AUDIO_SERVICE);
        if (am == null) return;
        if (Build.VERSION.SDK_INT >= 26 && focusRequest != null) {
            am.abandonAudioFocusRequest(focusRequest);
        } else {
            am.abandonAudioFocus(focusListener);
        }
    }

    private void pauseMusic() {
        if (music != null && music.isPlaying()) music.pause();
    }

    private void resumeMusic() {
        if (music != null && !music.isPlaying() && isMusicOn() && appInForeground) playCurrent();
    }

    private void stopMusic() {
        releaseMusic();
        abandonFocus();
    }

    private void releaseMusic() {
        if (music == null) return;
        try {
            music.stop();
        } catch (RuntimeException ignored) {
            // Already stopped or never prepared.
        }
        music.release();
        music = null;
    }

    // ---- App lifecycle ----

    /**
     * Called from the Application when the app goes to the background (no started activity left) or
     * returns. Music pauses in the background and resumes in the foreground when it was playing.
     */
    public synchronized void onAppForegroundChanged(boolean foreground) {
        appInForeground = foreground;
        if (foreground) {
            if (musicPausedByApp) resumeMusic();
            musicPausedByApp = false;
        } else {
            musicPausedByApp = music != null && music.isPlaying();
            pauseMusic();
        }
    }
}
